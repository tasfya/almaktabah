# frozen_string_literal: true

require "rails_helper"
require_relative "url_contract/fixed_content"

# The public show URLs, as Google has indexed them. Each expected path is a
# literal string, so a change to a route, an Arabic segment in ar.yml or the
# slug format fails here even though every route helper still agrees with
# itself.
RSpec.describe "Public URL contract", type: :request do
  include_context "with fixed url contract content"

  {
    book: -> { book_path(scholar, book) },
    article: -> { article_path(scholar, article) },
    series: -> { series_path(scholar, series) },
    lesson: -> { series_lesson_path(scholar, series, lesson) },
    news: -> { news_path(scholar, news) },
    fatwa: -> { fatwa_path(scholar, fatwa) },
    sermon: -> { lecture_path(scholar, sermon, kind: sermon.kind_for_url) },
    conference: -> { lecture_path(scholar, conference, kind: conference.kind_for_url) },
    benefit: -> { lecture_path(scholar, benefit, kind: benefit.kind_for_url) }
  }.each do |type, app_path|
    describe "#{type} show" do
      let(:literal) { UrlContract::SHOW_PATHS.fetch(type) }

      it "is generated by the app as the pinned literal path" do
        expect(instance_exec(&app_path)).to eq(literal)
      end

      it "serves the pinned literal path" do
        get literal
        expect(response).to have_http_status(:ok)
      end
    end
  end

  it "pins the lecture kind segments used by Lecture#kind_for_url" do
    expect([ sermon, conference, benefit ].map(&:kind_for_url).map { |k| URI::DEFAULT_PARSER.escape(k) })
      .to eq([ UrlContract::KIND_SERMON, UrlContract::KIND_CONFERENCE, UrlContract::KIND_BENEFIT ])
  end

  describe "index pages" do
    {
      "/#{UrlContract::BOOKS}" => -> { books_path },
      "/#{UrlContract::ARTICLES}" => -> { articles_path },
      "/#{UrlContract::SERIES}" => -> { series_index_path },
      "/#{UrlContract::LECTURES}" => -> { lectures_path },
      "/#{UrlContract::NEWS}" => -> { news_index_path },
      "/#{UrlContract::FATWAS}" => -> { fatwas_path },
      "/about" => -> { about_path },
      "/" => -> { root_path },
      "/sitemap.xml" => -> { "/sitemap.xml" },
      "/podcasts/feed" => -> { podcast_feed_path }
    }.each do |literal, app_path|
      it "generates #{literal} as a literal path" do
        expect(instance_exec(&app_path)).to eq(literal)
      end
    end
  end
end
